import fs from "node:fs";
import path from "node:path";

const root = process.cwd();
const outputPath = path.join(root, "lib", "generated", "pdf-fonts.ts");

const fonts = {
  latinRegular: path.join(
    root,
    "node_modules",
    "@fontsource",
    "noto-sans",
    "files",
    "noto-sans-latin-400-normal.woff",
  ),
  latinBold: path.join(
    root,
    "node_modules",
    "@fontsource",
    "noto-sans",
    "files",
    "noto-sans-latin-700-normal.woff",
  ),
  devanagariRegular: path.join(
    root,
    "node_modules",
    "@fontsource",
    "noto-sans",
    "files",
    "noto-sans-devanagari-400-normal.woff",
  ),
  devanagariBold: path.join(
    root,
    "node_modules",
    "@fontsource",
    "noto-sans",
    "files",
    "noto-sans-devanagari-700-normal.woff",
  ),
};

for (const [name, fontPath] of Object.entries(fonts)) {
  if (!fs.existsSync(fontPath)) {
    throw new Error(`Missing PDF font asset: ${name} at ${fontPath}`);
  }
}

const encoded = Object.fromEntries(
  Object.entries(fonts).map(([name, fontPath]) => [
    name,
    fs.readFileSync(fontPath).toString("base64"),
  ]),
);

fs.mkdirSync(path.dirname(outputPath), { recursive: true });
fs.writeFileSync(
  outputPath,
  `// Generated by scripts/prepare-pdf-fonts.mjs. Do not edit by hand.
export const PDF_FONT_BASE64 = ${JSON.stringify(encoded, null, 2)} as const;
`,
);

console.log("Prepared PDF font assets.");
